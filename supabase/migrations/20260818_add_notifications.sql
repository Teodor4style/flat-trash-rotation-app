begin;

-- =========================================================
-- 1. Notification records
-- =========================================================

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  recipient_id uuid not null
    references public.profiles(id) on delete cascade,
  type text not null,
  title text not null,
  body text not null,
  trash_id text
    references public.trash_types(id) on delete set null,
  actor_id uuid
    references public.profiles(id) on delete set null,
  target_person_id uuid
    references public.profiles(id) on delete set null,
  url text not null default '/',
  read_at timestamptz,
  push_processed_at timestamptz,
  push_attempts integer not null default 0,
  last_push_error text,
  created_at timestamptz not null default now()
);

create index if not exists notifications_recipient_created_idx
  on public.notifications (recipient_id, created_at desc);

create index if not exists notifications_unread_idx
  on public.notifications (recipient_id, created_at desc)
  where read_at is null;

create index if not exists notifications_pending_push_idx
  on public.notifications (created_at)
  where push_processed_at is null;


-- =========================================================
-- 2. Web Push subscriptions
-- =========================================================

create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null
    references public.profiles(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  user_agent text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists push_subscriptions_user_idx
  on public.push_subscriptions (user_id);


-- =========================================================
-- 3. Row Level Security
-- =========================================================

alter table public.notifications enable row level security;
alter table public.push_subscriptions enable row level security;

drop policy if exists "Members can read their notifications"
  on public.notifications;

create policy "Members can read their notifications"
  on public.notifications
  for select
  to authenticated
  using (recipient_id = auth.uid());

drop policy if exists "Members can read their push subscriptions"
  on public.push_subscriptions;

create policy "Members can read their push subscriptions"
  on public.push_subscriptions
  for select
  to authenticated
  using (user_id = auth.uid());

revoke all on table public.notifications from anon, authenticated;
revoke all on table public.push_subscriptions from anon, authenticated;

grant select on table public.notifications to authenticated;
grant select on table public.push_subscriptions to authenticated;


-- =========================================================
-- 4. Register a device for Web Push
-- =========================================================

create or replace function public.register_push_subscription(
  p_endpoint text,
  p_p256dh text,
  p_auth text,
  p_user_agent text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
begin
  if v_user_id is null then
    raise exception 'You must be signed in.';
  end if;

  if nullif(trim(p_endpoint), '') is null
     or nullif(trim(p_p256dh), '') is null
     or nullif(trim(p_auth), '') is null then
    raise exception 'The push subscription is incomplete.';
  end if;

  insert into public.push_subscriptions (
    user_id,
    endpoint,
    p256dh,
    auth,
    user_agent,
    updated_at
  )
  values (
    v_user_id,
    p_endpoint,
    p_p256dh,
    p_auth,
    p_user_agent,
    now()
  )
  on conflict (endpoint)
  do update set
    user_id = excluded.user_id,
    p256dh = excluded.p256dh,
    auth = excluded.auth,
    user_agent = excluded.user_agent,
    updated_at = now();
end;
$$;


-- =========================================================
-- 5. Unregister a device
-- =========================================================

create or replace function public.unregister_push_subscription(
  p_endpoint text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
begin
  if v_user_id is null then
    raise exception 'You must be signed in.';
  end if;

  delete from public.push_subscriptions
  where user_id = v_user_id
    and endpoint = p_endpoint;
end;
$$;


-- =========================================================
-- 6. Mark one notification as read
-- =========================================================

create or replace function public.mark_notification_read(
  p_notification_id bigint
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
begin
  if v_user_id is null then
    raise exception 'You must be signed in.';
  end if;

  update public.notifications
  set read_at = coalesce(read_at, now())
  where id = p_notification_id
    and recipient_id = v_user_id;
end;
$$;


