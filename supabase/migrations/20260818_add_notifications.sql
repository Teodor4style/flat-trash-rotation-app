-- =========================================================
-- 8. Update trash status and create an alert
-- =========================================================

create or replace function public.set_trash_status(
  p_trash_id text,
  p_status text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor uuid := auth.uid();
  v_actor_name text;
  v_old_status text;
  v_trash_name text;
  v_assignee uuid;
begin
  if v_actor is null then
    raise exception 'You must be signed in.';
  end if;

  if p_status not in ('ok', 'getting_full', 'needs_taking') then
    raise exception 'Invalid trash status.';
  end if;

  select
    status,
    name,
    next_person
  into
    v_old_status,
    v_trash_name,
    v_assignee
  from public.trash_types
  where id = p_trash_id
  for update;

  if not found then
    raise exception 'Trash category not found.';
  end if;

  if v_old_status = p_status then
    return;
  end if;

  select display_name
  into v_actor_name
  from public.profiles
  where id = v_actor;

  update public.trash_types
  set
    status = p_status,
    updated_at = now()
  where id = p_trash_id;

  insert into public.activity_log (
    type,
    actor_id,
    trash_id,
    from_status,
    to_status,
    summary
  )
  values (
    'status',
    v_actor,
    p_trash_id,
    v_old_status,
    p_status,
    coalesce(v_actor_name, 'Someone')
      || ' changed '
      || v_trash_name
      || ' from '
      || replace(v_old_status, '_', ' ')
      || ' to '
      || replace(p_status, '_', ' ')
  );

  if p_status = 'needs_taking'
     and v_assignee is not null then
    insert into public.notifications (
      recipient_id,
      type,
      title,
      body,
      trash_id,
      actor_id,
      target_person_id,
      url
    )
    values (
      v_assignee,
      'trash_needs_taking',
      '🗑️ ' || v_trash_name || ' needs taking',
      'It is your turn to take out ' || v_trash_name || '.',
      p_trash_id,
      v_actor,
      v_assignee,
      '/'
    );
  end if;
end;
$$;


-- =========================================================
-- 9. Availability changes and reassignment notifications
-- =========================================================

create or replace function public.set_availability(
  p_target_person uuid,
  p_availability text,
  p_away_until date default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor uuid := auth.uid();
  v_actor_name text;
  v_target_name text;
  v_actor_role text;
  v_replacement uuid;
  r record;
begin
  if v_actor is null then
    raise exception 'You must be signed in.';
  end if;

  if p_availability not in ('home', 'away') then
    raise exception 'Invalid availability value.';
  end if;

  select role, display_name
  into v_actor_role, v_actor_name
  from public.profiles
  where id = v_actor;

  if v_actor <> p_target_person
     and v_actor_role <> 'admin' then
    raise exception 'Only an administrator can change another member.';
  end if;

  select display_name
  into v_target_name
  from public.profiles
  where id = p_target_person;

  if not found then
    raise exception 'Member not found.';
  end if;

  update public.profiles
  set
    availability = p_availability,
    away_until = case
      when p_availability = 'away' then p_away_until
      else null
    end
  where id = p_target_person;

  if p_availability = 'away' then
    v_replacement :=
      public.next_available_after(p_target_person);

    if v_replacement is not null
       and v_replacement <> p_target_person then

      for r in
        select
          id,
          name,
          status
        from public.trash_types
        where next_person = p_target_person
        for update
      loop
        update public.trash_types
        set
          next_person = v_replacement,
          updated_at = now()
        where id = r.id;

        if r.status = 'needs_taking' then
          insert into public.notifications (
            recipient_id,
            type,
            title,
            body,
            trash_id,
            actor_id,
            target_person_id,
            url
          )
          values (
            v_replacement,
            'trash_reassigned',
            '🗑️ ' || r.name || ' needs taking',
            v_target_name
              || ' is away, so it is now your turn to take out '
              || r.name
              || '.',
            r.id,
            v_actor,
            v_replacement,
            '/'
          );
        end if;
      end loop;
    end if;
  end if;

  insert into public.activity_log (
    type,
    actor_id,
    target_person_id,
    summary
  )
  values (
    'vacation',
    v_actor,
    p_target_person,
    coalesce(v_actor_name, 'Someone')
      || ' set '
      || v_target_name
      || ' as '
      || p_availability
      || case
           when p_availability = 'away'
                and p_away_until is not null
           then ' until ' || p_away_until::text
           else ''
         end
  );
end;
$$;


