create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null check (username = lower(username)),
  display_name text not null,
  role text not null default 'member' check (role in ('admin','member')),
  availability text not null default 'home' check (availability in ('home','away')),
  away_until date,
  rotation_position integer not null,
  created_at timestamptz not null default now()
);

create table if not exists public.trash_types (
  id text primary key,
  name text not null,
  emoji text not null,
  sort_order integer unique not null,
  status text not null default 'ok' check (status in ('ok','getting_full','needs_taking')),
  next_person uuid references public.profiles(id),
  last_taken_by uuid references public.profiles(id),
  last_taken_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.activity_log (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  type text not null check (type in ('taken','status','vacation','password_reset','admin')),
  actor_id uuid references public.profiles(id),
  trash_id text references public.trash_types(id),
  expected_person_id uuid references public.profiles(id),
  actual_person_id uuid references public.profiles(id),
  target_person_id uuid references public.profiles(id),
  voluntary boolean,
  from_status text,
  to_status text,
  summary text not null
);

